import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { State, saveJson, readJson, acquireLock } from '../src/state.js';
const script = fileURLToPath(new URL('../scripts/prepare-rollback.js', import.meta.url));
test('rollback refuses active service, mismatched accounts and pending work, then backs up and migrates only cursor/context', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'wechat-rollback-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const accountFile = path.join(dir, 'old', 'bot.json');
  const original = { token: 'fixture-token', user_id: 'fixture-owner' };
  saveJson(accountFile, original);
  const stateDir = path.join(dir, 'new');
  const account = { token: original.token, userId: original.user_id, importedFrom: accountFile };
  saveJson(path.join(stateDir, 'account.json'), account);
  saveJson(path.join(dir, 'old', 'bot.sync.json'), { get_updates_buf: 'old-cursor' });
  saveJson(path.join(dir, 'old', 'bot.context-tokens.json'), { other: 'keep' });
  const state = new State(stateDir); state.data.cursor = 'new-cursor'; state.chat(account.userId).contextToken = 'new-context'; state.save();
  const run = () => spawnSync(process.execPath, [script], { env: { ...process.env, WECHAT_CODEX_STATE: stateDir }, encoding: 'utf8' });
  const unlock = acquireLock(stateDir); assert.notEqual(run().status, 0); unlock();
  saveJson(accountFile, { ...original, token: 'changed' }); assert.notEqual(run().status, 0); saveJson(accountFile, original);
  state.data.inbox.push({ status: 'queued' }); state.save(); assert.notEqual(run().status, 0); state.data.inbox = [];
  state.data.threads.example = { lastTurnStatus: 'inProgress' }; state.save(); assert.notEqual(run().status, 0);
  state.data.threads.example.lastTurnStatus = 'completed'; state.save();
  const result = run(); assert.equal(result.status, 0, result.stderr);
  assert.deepEqual(readJson(accountFile), original);
  assert.equal(readJson(path.join(dir, 'old', 'bot.sync.json')).get_updates_buf, 'new-cursor');
  assert.deepEqual(readJson(path.join(dir, 'old', 'bot.context-tokens.json')), { other: 'keep', 'fixture-owner': 'new-context' });
  const backups = fs.readdirSync(path.join(dir, 'old')).filter(n => n.includes('.before-wechat-codex-rollback-'));
  assert.equal(backups.length, 2);
  for (const name of backups) assert.equal(fs.statSync(path.join(dir, 'old', name)).mode & 0o777, 0o600);
});
